#!/usr/bin/env python3
"""Compare native ASH and ash_pes2d fast xTB point-charge I/O.

Runs the same native ASH example cases with xTB 6.8.0 and records energy,
gradient, end-to-end runtime, plus repeated timings of the point-charge writer
and pcgrad reader using the exact arrays/files produced by each example.
"""
import argparse
import hashlib
import json
import os
import shutil
import statistics
import sys
import time
from pathlib import Path

import numpy as np


def parse_args():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--ash-root", type=Path, default=Path(__file__).resolve().parents[2])
    p.add_argument("--xtb-dir", type=Path, default=None,
                    help="directory holding the xtb executable (default: the xtb found on PATH)")
    p.add_argument("--ash-pes2d", type=Path, default=None,
                   help="checkout that provides the ash_pes2d package (default: import from PYTHONPATH)")
    p.add_argument("--workdir", type=Path, default=Path("/tmp/ash-native-io-benchmark"))
    p.add_argument("--repetitions", type=int, default=25,
                   help="repetitions for isolated writer and reader timings")
    p.add_argument("--prepared", type=Path, default=Path(__file__).resolve().parent / "prepared",
                   help="directory with inputs generated by prepare_inputs.sh")
    p.add_argument("--cases", nargs="+", choices=tuple(CASES), default=tuple(CASES))
    return p.parse_args()


